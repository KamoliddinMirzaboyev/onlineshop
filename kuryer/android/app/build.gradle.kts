            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    // Play: 16 KB page size / packaging
    packaging {
        jniLibs {
            useLegacyPackaging = false
        }
    }
}

